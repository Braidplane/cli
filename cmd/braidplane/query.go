type listQueriesCommand struct {
	queryDataSourceFlags

	Limit          int32  `help:"Maximum number of queries to return." name:"limit"`
	Cursor         string `help:"Pagination cursor from a previous list response." name:"cursor"`
	SortBy         string `help:"Sort field: query_created_at, query_name, or query_updated_at." name:"sort-by"`
	Order          string `help:"Sort order: asc or desc." name:"order"`
	Direction      string `help:"Pagination direction: next or prev." name:"direction"`
	IncludeDeleted bool   `help:"Include soft-deleted queries." name:"include-deleted"`
}

// Run lists saved queries for one concrete data source.
func (c *listQueriesCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}

	params, err := listQueriesParams(c.Limit, c.Cursor, c.SortBy, c.Order, c.Direction, c.IncludeDeleted)
	if err != nil {
		return err
	}
	queries, err := client.listQueries(context.Background(), c.DataSourceSlug, params)
	if err != nil {
		return xerror.Wrapf("list queries for %s: %w", c.DataSourceSlug, err)
	}

	return writeCLIJSON(output.stdout, queries)
}

