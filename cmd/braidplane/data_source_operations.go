type dataSourceProviderOnboardCommand struct {
	apiAuthFlags
	Provider       string `arg:"" name:"provider" help:"Backend-registered provider key: hubspot or gitlab." required:""`
	Name           string `help:"Data-source display name." name:"name" required:""`
	Slug           string `help:"Data-source slug. Generated by the API when omitted." name:"slug"`
	TimeoutSeconds int    `help:"Provider API timeout in seconds." name:"timeout-seconds"`
	BasePath       string `help:"Base path within the GitLab repository." name:"base-path"`
	ReadOnly       bool   `help:"Request a read-only provider grant." name:"read-only" default:"true"`
}

func (c *dataSourceProviderOnboardCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	provider := strings.ToLower(strings.TrimSpace(c.Provider))
	body := api.StartProviderDataSourceInstallRequest{Name: c.Name, Slug: optionalAPISlug(c.Slug)}
	body.ReadOnly = &c.ReadOnly
	switch provider {
	case "hubspot":
		if c.TimeoutSeconds < 0 {
			return xerror.InvalidInput(xerror.DataSource).Detail("timeout-seconds must be positive")
		}
		config := api.HubSpotConfig{}
		if c.TimeoutSeconds > 0 {
			config.TimeoutSeconds = &c.TimeoutSeconds
		}
		body.Type = api.StartProviderDataSourceInstallRequestTypeHubspot
		if err := body.Config.FromHubSpotConfig(config); err != nil {
			return xerror.Unexpected().With(err)
		}
	case "gitlab":
		body.Type = api.StartProviderDataSourceInstallRequestTypeGitlab
		config := api.ProviderGitOnboardingConfig{
			Provider: api.ProviderGitOnboardingConfigProviderGitlab,
			BasePath: optionalString(c.BasePath),
		}
		if err := body.Config.FromProviderGitOnboardingConfig(config); err != nil {
			return xerror.Unexpected().With(err)
		}
	default:
		return xerror.InvalidInput(xerror.DataSource).Detail("provider must be hubspot or gitlab")
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	install, err := client.startProviderDataSourceInstall(context.Background(), provider, body)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, install)
}

type dataSourceProviderInstallCommand struct {
	apiAuthFlags
	Provider       string `arg:"" name:"provider" help:"Backend-registered provider key. Current supported value: hubspot." required:""`
	DataSourceSlug string `arg:"" name:"data-source-slug" help:"Existing provider-backed data-source slug." required:""`
	Intent         string `help:"Install intent: create_grant or rotate_grant." name:"intent" default:"create_grant"`
}

func (c *dataSourceProviderInstallCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	intent := api.ProviderInstallIntent(strings.ToLower(strings.TrimSpace(c.Intent)))
	if !intent.Valid() {
		return xerror.InvalidInput(xerror.DataSource).Detail("intent must be create_grant or rotate_grant")
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	install, err := client.startProviderConnectorInstall(context.Background(), strings.ToLower(strings.TrimSpace(c.Provider)), api.StartProviderConnectorInstallRequest{DataSourceSlug: c.DataSourceSlug, Intent: intent})
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, install)
}

