type dataSourceProviderOnboardCommand struct {
	apiAuthFlags
	Provider       string `arg:"" name:"provider" help:"Backend-registered provider key: hubspot or google_workspace (rollout)." required:""`
	Name           string `help:"Data-source display name." name:"name" required:""`
	Slug           string `help:"Data-source slug. Generated by the API when omitted." name:"slug"`
	TimeoutSeconds int    `help:"Provider API timeout in seconds." name:"timeout-seconds"`
	ReadOnly       bool   `help:"Request a read-only provider grant." name:"read-only" default:"true"`
}

func (c *dataSourceProviderOnboardCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	provider := strings.ToLower(strings.TrimSpace(c.Provider))
	body := api.StartProviderDataSourceInstallRequest{Name: c.Name, Slug: optionalAPISlug(c.Slug)}
	body.ReadOnly = &c.ReadOnly
	switch provider {
	case "google_workspace":
		config := workspace.PendingInstallConfig{AccessMode: workspace.SelectedFiles}
		if err := config.Validate(); err != nil {
			return xerror.InvalidInput(xerror.DataSource).With(err)
		}
		if c.TimeoutSeconds != 0 {
			return xerror.InvalidInput(xerror.DataSource).Detail("timeout-seconds is not a Workspace config field")
		}
		body.Type = api.StartProviderDataSourceInstallRequestTypeGoogleWorkspace
		if err := body.Config.FromGoogleWorkspacePendingInstallConfig(api.GoogleWorkspacePendingInstallConfig{AccessMode: workspaceAccessModePointer(workspace.SelectedFiles)}); err != nil {
			return err
		}
	case "hubspot":
		if c.TimeoutSeconds < 0 {
			return xerror.InvalidInput(xerror.DataSource).Detail("timeout-seconds must be positive")
		}
		config := api.HubSpotConfig{}
		if c.TimeoutSeconds > 0 {
			config.TimeoutSeconds = &c.TimeoutSeconds
		}
		body.Type = api.StartProviderDataSourceInstallRequestTypeHubspot
		if err := body.Config.FromHubSpotConfig(config); err != nil {
			return xerror.Unexpected().With(err)
		}
	case "gitlab":
		return xerror.InvalidInput(xerror.DataSource).Detail("Connect GitLab in organization settings, then create a managed data source with the selected project_id. Use Generic Git for manual credentials.")
	default:
		return xerror.InvalidInput(xerror.DataSource).Detail("provider must be hubspot or google_workspace")
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	install, err := client.startProviderDataSourceInstall(context.Background(), provider, body)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, install)
}

