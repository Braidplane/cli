type dataSourceWorkspaceFilesCommand struct {
	apiAuthFlags
	DataSourceSlug string `arg:"" name:"data-source-slug" required:""`
	FolderID       string `help:"Only files in this Google Drive folder." name:"folder-id"`
	DriveID        string `help:"Only files in this shared drive." name:"drive-id"`
	MIMEType       string `help:"Only files with this MIME type." name:"mime-type"`
	PageToken      string `help:"Opaque continuation token from the previous page." name:"page-token"`
}

func (c *dataSourceWorkspaceFilesCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	params := &api.ListGoogleWorkspaceFilesParams{}
	if c.FolderID != "" {
		params.FolderId = &c.FolderID
	}
	if c.DriveID != "" {
		params.DriveId = &c.DriveID
	}
	if c.MIMEType != "" {
		params.MimeType = &c.MIMEType
	}
	if c.PageToken != "" {
		params.PageToken = &c.PageToken
	}
	response, err := client.openapi.ListGoogleWorkspaceFilesWithResponse(context.Background(), client.organization, c.DataSourceSlug, params)
	if err != nil {
		return xerror.Wrapf("list Google Workspace files: %w", err)
	}
	if response.StatusCode() != http.StatusOK {
		return decodeAPIError(response.StatusCode(), response.Body)
	}
	if response.JSON200 == nil {
		return xerror.Unexpected().Detail("Missing Google Workspace file discovery response")
	}
	return writeCLIJSON(output.stdout, response.JSON200)
}

type dataSourceWorkspaceVerifyCommand struct {
	apiAuthFlags
	DataSourceSlug string   `arg:"" required:""`
	FileIDs        []string `help:"Google file ID; repeat for each file." name:"file-id" required:""`
}

func (c *dataSourceWorkspaceVerifyCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	source, err := client.openapi.GetDataSourceWithResponse(context.Background(), client.organization, c.DataSourceSlug)
	if err != nil {
		return xerror.Unexpected().With(err).Detail("load Workspace verification revision")
	}
	if source.StatusCode() != http.StatusOK {
		return decodeAPIError(source.StatusCode(), source.Body)
	}
	if source.JSON200 == nil || source.JSON200.ConnectionRevision == nil {
		return xerror.InvalidInput(xerror.DataSource).Detail("Cannot load current Workspace verification revision")
	}
	response, err := client.openapi.VerifyGoogleWorkspaceFilesWithResponse(context.Background(), client.organization, c.DataSourceSlug, api.GoogleWorkspaceVerificationRequest{FileIds: c.FileIDs, ExpectedRevision: *source.JSON200.ConnectionRevision})
	if err != nil {
		return xerror.Unexpected().With(err).Detail("verify Google Workspace files")
	}
	if response.StatusCode() != http.StatusOK {
		return decodeAPIError(response.StatusCode(), response.Body)
	}
	if response.JSON200 == nil {
		return xerror.Unexpected().Detail("unexpected API response: missing Google Workspace verification payload")
	}
	return writeCLIJSON(output.stdout, response.JSON200)
}

