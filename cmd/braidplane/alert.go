// applyAlertListBasics validates shared list pagination flags.
func applyAlertListBasics(
	limit *int32,
	cursor string,
	maxLimit int32,
	outLimit **api.LimitParam,
	outCursor **api.CursorParam,
) error {
	if limit != nil {
		if *limit < 1 || *limit > maxLimit {
			return xerror.ValidationFailed().Detail("limit must be between 1 and 100")
		}
		value := *limit
		*outLimit = &value
	}
	if cursor != "" {
		value := cursor
		*outCursor = &value
	}
	return nil
}

// emailAlertDestinationConfig builds the non-secret email destination config union.
func emailAlertDestinationConfig(rawRecipients []string) (api.AlertDestinationConfig, error) {
	recipients := make([]api.Email, 0, len(rawRecipients))
	for _, raw := range rawRecipients {
		recipient := strings.TrimSpace(raw)
		if recipient == "" {
			continue
		}
		recipients = append(recipients, api.Email(recipient))
	}
	if len(recipients) == 0 {
		return api.AlertDestinationConfig{}, xerror.ValidationFailed().Detail("set --recipient")
	}

	config := api.AlertDestinationConfig{}
	if err := config.FromEmailAlertDestinationConfig(api.EmailAlertDestinationConfig{Recipients: recipients}); err != nil {
		return api.AlertDestinationConfig{}, xerror.Unexpected().Detailf("encode email destination config: %w", err)
	}
	return config, nil
}

// requiredAlertName trims a CLI name flag and rejects empty display names before API calls.
func requiredAlertName(raw string) (string, error) {
	name := strings.TrimSpace(raw)
	if name == "" {
		return "", xerror.ValidationFailed().Detail("set --name")
	}
	return name, nil
}

// explicitAlertEnabled requires update callers to choose enabled state intentionally.
func explicitAlertEnabled(enabled, disabled bool) (bool, error) {
	switch {
	case enabled && disabled:
		return false, xerror.ValidationFailed().Detail("only one of --enabled or --disabled can be set")
	case enabled:
		return true, nil
	case disabled:
		return false, nil
	default:
		return false, xerror.ValidationFailed().Detail("set --enabled or --disabled")
	}
}

// apiSlugsFromStrings trims and validates slug-like repeated CLI flag values.
func apiSlugsFromStrings(rawValues []string, missingDetail string) ([]api.Slug, error) {
	ret := make([]api.Slug, 0, len(rawValues))
	seen := map[string]struct{}{}
	for _, raw := range rawValues {
		value := strings.TrimSpace(raw)
		if value == "" {
			continue
		}
		if _, ok := seen[value]; ok {
			return nil, xerror.ValidationFailed().Detail("destination slugs must be unique")
		}
		seen[value] = struct{}{}
		ret = append(ret, value)
	}
	if len(ret) == 0 {
		return nil, xerror.ValidationFailed().Detail(missingDetail)
	}
	return ret, nil
}

// applyAlertPolicyScope sets project and environment selectors allowed by the selected policy scope.
func applyAlertPolicyScope(body *alertPolicySharedBody, projectSlug, environmentSlug string) error {
	projectSlug = strings.TrimSpace(projectSlug)
	environmentSlug = strings.TrimSpace(environmentSlug)
	switch body.Scope {
	case api.AlertPolicyScopeOrganization:
		if projectSlug != "" || environmentSlug != "" {
			return xerror.ValidationFailed().Detail("organization scope must not include --project or --environment")
		}
	case api.AlertPolicyScopeProject:
		if projectSlug == "" {
			return xerror.ValidationFailed().Detail("set --project for project scope")
		}
		if environmentSlug != "" {
			return xerror.ValidationFailed().Detail("project scope must not include --environment")
		}
		value := projectSlug
		body.ProjectSlug = &value
	case api.AlertPolicyScopeProjectEnvironment:
		if projectSlug == "" {
			return xerror.ValidationFailed().Detail("set --project for project_environment scope")
		}
		if environmentSlug == "" {
			return xerror.ValidationFailed().Detail("set --environment for project_environment scope")
		}
		projectValue := projectSlug
		environmentValue := environmentSlug
		body.ProjectSlug = &projectValue
		body.EnvironmentSlug = &environmentValue
	default:
		return xerror.ValidationFailed().Detail("scope must be organization, project, or project_environment")
	}
	return nil
}

// applyAlertPolicySelectors validates optional selectors and attaches them to the policy body.
func applyAlertPolicySelectors(body *alertPolicySharedBody, f alertPolicyBodyFlags) error {
	if f.NotificationType != "" {
		value := api.AlertPolicyNotificationType(f.NotificationType)
		if !value.Valid() || value == api.NotificationTypeUnknown {
			return xerror.ValidationFailed().Detail("notification-type must be a supported API enum value; use pipeline capabilities to discover available producers")
		}
		body.NotificationType = &value
	}
	if f.Severity != "" {
		value := api.AlertPolicySeverity(f.Severity)
		if !value.Valid() || value == api.NotificationSeverityUnknown {
			return xerror.ValidationFailed().Detail("severity must be info, warning, or critical")
		}
		body.Severity = &value
	}
	if f.LifecycleState != "" {
		value := api.AlertPolicyLifecycleState(f.LifecycleState)
		if !value.Valid() || value == api.NotificationLifecycleStateUnknown {
			return xerror.ValidationFailed().Detail("lifecycle-state must be open, acknowledged, or resolved")
		}
		body.LifecycleState = &value
	}
	if f.SourceKind != "" {
		value := api.AlertPolicySourceKind(f.SourceKind)
		if !value.Valid() || value == api.EventEntityTypeUnknown {
			return xerror.ValidationFailed().Detail("source-kind must be a supported event entity type")
		}
		body.SourceKind = &value
	}
	if f.SourceAction != "" {
		if f.SourceKind == "" {
			return xerror.ValidationFailed().Detail("source-action requires source-kind")
		}
		value := api.AlertPolicySourceAction(f.SourceAction)
		if !value.Valid() || value == api.EventActionUnknown {
			return xerror.ValidationFailed().Detail("source-action must be a supported event action")
		}
		body.SourceAction = &value
	}
	if f.SourceRef != "" {
		if f.SourceKind == "" {
			return xerror.ValidationFailed().Detail("source-ref requires source-kind")
		}
		value := strings.TrimSpace(f.SourceRef)
		body.SourceRef = &value
	}
	return nil
}

func (c *cliAPIClient) requireRecencyNotificationCapability(ctx context.Context, kind *api.AlertPolicyNotificationType) error {
	if kind == nil || *kind != api.NotificationTypePipelineFreshnessSLABreached {
		return nil
	}
	capabilities, err := c.pipelineOperationalCapabilities(ctx)
	if err != nil {
		return err
	}
	for _, supported := range capabilities.NotificationTypes {
		if supported == *kind {
			return nil
		}
	}
	return xerror.ValidationFailed().Detail("successful-run recency notifications are unavailable on this server")
}
