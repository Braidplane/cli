// alertDestinationListParams converts common destination list flags to OpenAPI parameters.
func alertDestinationListParams(
	limit *int32,
	cursor string,
	direction string,
	sortBy string,
	order string,
) (api.ListAlertDestinationsParams, error) {
	params := api.ListAlertDestinationsParams{}
	if err := applyAlertListBasics(limit, cursor, maxAlertListLimit, &params.Limit, &params.Cursor); err != nil {
		return params, err
	}
	if direction != "" {
		value := api.ListAlertDestinationsParamsDirection(direction)
		if !value.Valid() {
			return params, xerror.ValidationFailed().Detail("direction must be next or prev")
		}
		params.Direction = &value
	}
	if sortBy != "" {
		value := api.ListAlertDestinationsParamsSortBy(sortBy)
		if !value.Valid() {
			return params, xerror.ValidationFailed().Detail("sort-by must be alert_destination_created_at")
		}
		params.SortBy = &value
	}
	if order != "" {
		value := api.ListAlertDestinationsParamsOrder(order)
		if !value.Valid() {
			return params, xerror.ValidationFailed().Detail("order must be asc or desc")
		}
		params.Order = &value
	}
	return params, nil
}

