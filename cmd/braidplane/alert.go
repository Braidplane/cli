type alertPolicySharedBody struct {
	Name             string
	Scope            api.AlertPolicyScope
	ProjectSlug      *api.Slug
	EnvironmentSlug  *api.Slug
	NotificationType *api.AlertPolicyNotificationType
	Severity         *api.AlertPolicySeverity
	LifecycleState   *api.AlertPolicyLifecycleState
	SourceKind       *api.AlertPolicySourceKind
	SourceAction     *api.AlertPolicySourceAction
	SourceRef        *api.AlertPolicySourceRef
	DestinationSlugs []api.Slug
}

// sharedBody maps alert policy flags into reusable create/update payload fields.
func (f alertPolicyBodyFlags) sharedBody() (alertPolicySharedBody, error) {
	name, err := requiredAlertName(f.Name)
	if err != nil {
		return alertPolicySharedBody{}, err
	}
	destinationSlugs, err := apiSlugsFromStrings(f.DestinationSlug, "set --destination")
	if err != nil {
		return alertPolicySharedBody{}, err
	}
	body := alertPolicySharedBody{
		Name:             name,
		Scope:            api.AlertPolicyScope(f.Scope),
		DestinationSlugs: destinationSlugs,
	}

	if err := applyAlertPolicyScope(&body, f.ProjectSlug, f.EnvironmentSlug); err != nil {
		return alertPolicySharedBody{}, err
	}
	if err := applyAlertPolicySelectors(&body, f); err != nil {
		return alertPolicySharedBody{}, err
	}
	if body.NotificationType == nil && body.Severity == nil && body.SourceKind == nil {
		return alertPolicySharedBody{}, xerror.ValidationFailed().Detail("set --notification-type, --severity, or --source-kind")
	}

	return body, nil
}

// newAlertPolicy converts shared policy fields to the create request shape.
func (b alertPolicySharedBody) newAlertPolicy() api.NewAlertPolicy {
	return api.NewAlertPolicy{
		Name:             b.Name,
		Scope:            b.Scope,
		ProjectSlug:      b.ProjectSlug,
		EnvironmentSlug:  b.EnvironmentSlug,
		NotificationType: b.NotificationType,
		Severity:         b.Severity,
		LifecycleState:   b.LifecycleState,
		SourceKind:       b.SourceKind,
		SourceAction:     b.SourceAction,
		SourceRef:        b.SourceRef,
		DestinationSlugs: b.DestinationSlugs,
	}
}

// updateAlertPolicy converts shared policy fields to the full update request shape.
