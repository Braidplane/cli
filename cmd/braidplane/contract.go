type previewODCSRevisionImpactCommand struct {
	apiPipelineFlags
	ContractSlug string `arg:"" name:"contract-slug" help:"ODCS contract slug." required:""`
	From         string `help:"Existing immutable revision slug." name:"from" required:""`
	To           string `help:"Candidate immutable revision slug." name:"to" required:""`
	FromPipeline string `help:"Pipeline owning the exact source compiled plan." name:"from-pipeline"`
	FromPlan     string `help:"Exact retained source compiled plan digest; requires both pipeline/plan selections." name:"from-plan"`
	ToPipeline   string `help:"Pipeline owning the exact target compiled plan." name:"to-pipeline"`
	FromInput    *int   `help:"Exact source projection input index from retained plan inspection." name:"from-projection-input"`
	ToInput      *int   `help:"Exact target projection input index from retained plan inspection." name:"to-projection-input"`
	ToPlan       string `help:"Exact retained target compiled plan digest." name:"to-plan"`
}

func (c *previewODCSRevisionImpactCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, project, err := newPipelineAPIClient(c.apiPipelineFlags, runtime)
	if err != nil {
		return err
	}
	contract, err := requiredODCSSlug(c.ContractSlug, "contract slug")
	if err != nil {
		return err
	}
	from, err := requiredODCSSlug(c.From, "from revision slug")
	if err != nil {
		return err
	}
	to, err := requiredODCSSlug(c.To, "to revision slug")
	if err != nil {
		return err
	}
	request := api.ODCSRevisionImpactRequest{FromRevisionSlug: from, ToRevisionSlug: to}
	if c.FromPipeline != "" || c.FromPlan != "" || c.ToPipeline != "" || c.ToPlan != "" || c.FromInput != nil || c.ToInput != nil {
		fromPipeline, err := requiredODCSSlug(c.FromPipeline, "from pipeline")
		if err != nil {
			return err
		}
		toPipeline, err := requiredODCSSlug(c.ToPipeline, "to pipeline")
		if err != nil {
			return err
		}
		if c.FromPlan == "" || c.ToPlan == "" {
			return xerror.ValidationFailed().Detail("both exact plan digests are required")
		}
		request.FromPlan = &api.ODCSImpactPlanSelection{PipelineSlug: fromPipeline, Digest: c.FromPlan, ProjectionInput: c.FromInput}
		request.ToPlan = &api.ODCSImpactPlanSelection{PipelineSlug: toPipeline, Digest: c.ToPlan, ProjectionInput: c.ToInput}
	}
	result, err := client.previewODCSRevisionImpact(context.Background(), project, contract, request)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, result)
}

func odcsContractListParams(limit int32, cursor, order, direction string) (*api.ListODCSContractsParams, error) {
	params := &api.ListODCSContractsParams{}
	if err := applyLimitCursor(limit, cursor, &params.Limit, &params.Cursor); err != nil {
		return nil, err
	}
	if order := strings.TrimSpace(order); order != "" && order != "asc" && order != "desc" {
		return nil, xerror.ValidationFailed().Detail("order must be asc or desc")
	} else if order != "" {
		value := api.ListODCSContractsParamsOrder(order)
		params.Order = &value
	}
	if direction := strings.TrimSpace(direction); direction != "" && direction != "next" && direction != "prev" {
		return nil, xerror.ValidationFailed().Detail("direction must be next or prev")
	} else if direction != "" {
		value := api.ListODCSContractsParamsDirection(direction)
		params.Direction = &value
	}
	return params, nil
}

