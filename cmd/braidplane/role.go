type roleDefinitionFlags struct {
	Name        string   `help:"Role display name." name:"name" required:""`
	Permissions []string `help:"Permission as resource:action; pass a comma-separated list or repeat the flag." name:"permission" required:""`
}

func (f roleDefinitionFlags) apiPermissions() ([]api.Permission, error) {
	permissions := make([]api.Permission, 0, len(f.Permissions))
	for _, raw := range f.Permissions {
		resource, actionText, found := strings.Cut(raw, ":")
		resource = strings.TrimSpace(resource)
		action := api.PermissionAction(strings.TrimSpace(actionText))
		if !found || resource == "" || !action.Valid() {
			return nil, xerror.ValidationFailed().Detailf(
				"permission %q must use resource:action with a supported action", raw,
			)
		}
		permissions = append(permissions, api.Permission{Resource: resource, Action: action})
	}
	return permissions, nil
}

type createRoleCommand struct {
	apiAuthFlags
	roleDefinitionFlags
	Slug string `help:"Role slug. Generated by the API when omitted." name:"slug"`
}

func (c *createRoleCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	permissions, err := c.apiPermissions()
	if err != nil {
		return err
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	role, err := client.createRole(context.Background(), api.NewOrgRole{
		Name: c.Name, Slug: optionalAPISlug(c.Slug), Permissions: permissions,
	})
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, role)
}

