package main

import (
	"context"
	"strings"

	api "github.com/Braidplane/cli/internal/apiclient"
	"github.com/Braidplane/cli/pkg/xerror"
)

type roleCommand struct {
	List    listRolesCommand   `cmd:"" help:"List roles in the configured organization."`
	Get     getRoleCommand     `cmd:"" help:"Get an organization role."`
	Create  createRoleCommand  `cmd:"" help:"Create a custom organization role."`
	Update  updateRoleCommand  `cmd:"" help:"Replace a custom organization role's name and permissions."`
	Archive archiveRoleCommand `cmd:"" help:"Archive a custom organization role."`
	Restore restoreRoleCommand `cmd:"" help:"Restore an archived custom organization role."`
}

type listRolesCommand struct {
	apiAuthFlags
	iamPaginationFlags
	IncludeArchived bool `help:"Include archived roles." name:"include-archived"`
	OnlyArchived    bool `help:"Return only archived roles." name:"only-archived"`
}

func (c *listRolesCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	if err := c.validate(func(value string) bool {
		return api.ListRolesParamsSortBy(value).Valid()
	}); err != nil {
		return err
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	params := api.ListRolesParams{}
	setRolePagination(&params, c.iamPaginationFlags)
	if c.IncludeArchived {
		params.IncludeDeleted = &c.IncludeArchived
	}
	if c.OnlyArchived {
		params.OnlyDeleted = &c.OnlyArchived
	}
	roles, err := client.listRoles(context.Background(), &params)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, roles)
}

func setRolePagination(params *api.ListRolesParams, flags iamPaginationFlags) {
	if flags.Limit != 0 {
		value := flags.Limit
		params.Limit = &value
	}
	if flags.Cursor != "" {
		value := flags.Cursor
		params.Cursor = &value
	}
	if flags.SortBy != "" {
		value := api.ListRolesParamsSortBy(flags.SortBy)
		params.SortBy = &value
	}
	if flags.Order != "" {
		value := api.ListRolesParamsOrder(flags.Order)
		params.Order = &value
	}
	if flags.Direction != "" {
		value := api.ListRolesParamsDirection(flags.Direction)
		params.Direction = &value
	}
}

