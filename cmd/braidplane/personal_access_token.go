func parseCredentialExpiration(raw string) (api.NullableTimestamp, bool, error) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return api.NullableTimestamp{}, false, nil
	}
	value, err := time.Parse(time.RFC3339, raw)
	if err != nil {
		return api.NullableTimestamp{}, false, xerror.ValidationFailed().Detailf("expires-at must use RFC3339: %v", err)
	}
	return value, true, nil
}

func credentialUpdateBody(
	name string,
	description *string,
	clearDescription bool,
	expiresAt string,
	clearExpiration bool,
	currentDescription *string,
	currentExpiration *api.NullableTimestamp,
) ([]byte, error) {
	if description != nil && clearDescription {
		return nil, xerror.ValidationFailed().Detail("description and clear-description cannot be used together")
	}
	if strings.TrimSpace(expiresAt) != "" && clearExpiration {
		return nil, xerror.ValidationFailed().Detail("expires-at and clear-expiration cannot be used together")
	}

	body := map[string]any{"name": name}
	if currentDescription != nil {
		body["description"] = currentDescription
	}
	if currentExpiration != nil {
		body["expires_at"] = currentExpiration
	}
	if description != nil {
		body["description"] = *description
	} else if clearDescription {
		body["description"] = nil
	}
	if strings.TrimSpace(expiresAt) != "" {
		value, _, err := parseCredentialExpiration(expiresAt)
		if err != nil {
			return nil, err
		}
		body["expires_at"] = value
	} else if clearExpiration {
		body["expires_at"] = nil
	}

	encoded, err := json.Marshal(body)
	if err != nil {
		return nil, xerror.Wrapf("encode credential update: %w", err)
	}
	return encoded, nil
}
