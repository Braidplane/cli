type personalAccessTokenCommand struct {
	List   listPersonalAccessTokensCommand  `cmd:"" help:"List personal access token metadata (management-enabled PAT required)."`
	Get    getPersonalAccessTokenCommand    `cmd:"" help:"Get personal access token metadata (management-enabled PAT required)."`
	Create createPersonalAccessTokenCommand `cmd:"" help:"Create a non-delegating personal access token and print its secret once."`
	Update updatePersonalAccessTokenCommand `cmd:"" help:"Update personal access token metadata without changing management authority."`
	Rotate rotatePersonalAccessTokenCommand `cmd:"" help:"Rotate a personal access token and print its new secret once."`
	Revoke revokePersonalAccessTokenCommand `cmd:"" help:"Revoke a personal access token."`
}

type listPersonalAccessTokensCommand struct {
	accountAuthFlags
	iamPaginationFlags
}

func (c *listPersonalAccessTokensCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	if err := c.validate(func(value string) bool {
		return api.ListPersonalAccessTokensParamsSortBy(value).Valid()
	}); err != nil {
		return err
	}
	client, err := newAccountAPIClient(c.accountAuthFlags, runtime)
	if err != nil {
		return err
	}
	params := api.ListPersonalAccessTokensParams{}
	setPersonalAccessTokenPagination(&params, c.iamPaginationFlags)
	tokens, err := client.listPersonalAccessTokens(context.Background(), &params)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, tokens)
}

func setPersonalAccessTokenPagination(params *api.ListPersonalAccessTokensParams, flags iamPaginationFlags) {
	if flags.Limit != 0 {
		value := flags.Limit
		params.Limit = &value
	}
	if flags.Cursor != "" {
		value := flags.Cursor
		params.Cursor = &value
	}
	if flags.SortBy != "" {
		value := api.ListPersonalAccessTokensParamsSortBy(flags.SortBy)
		params.SortBy = &value
	}
	if flags.Order != "" {
		value := api.ListPersonalAccessTokensParamsOrder(flags.Order)
		params.Order = &value
	}
	if flags.Direction != "" {
		value := api.ListPersonalAccessTokensParamsDirection(flags.Direction)
		params.Direction = &value
	}
}

