type createPersonalAccessTokenCommand struct {
	accountAuthFlags
	Name        string  `help:"Personal access token display name." name:"name" required:""`
	Slug        string  `help:"Personal access token slug. Generated by the API when omitted." name:"slug"`
	Description *string `help:"Personal access token description." name:"description"`
	ExpiresAt   string  `help:"Optional RFC3339 expiration timestamp." name:"expires-at"`
}

func (c *createPersonalAccessTokenCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	expiresAt, hasExpiration, err := parseCredentialExpiration(c.ExpiresAt)
	if err != nil {
		return err
	}
	var expiresAtParam *api.NullableTimestamp
	if hasExpiration {
		expiresAtParam = &expiresAt
	}
	client, err := newAccountAPIClient(c.accountAuthFlags, runtime)
	if err != nil {
		return err
	}
	token, err := client.createPersonalAccessToken(context.Background(), api.NewPersonalAccessToken{
		Name:        c.Name,
		Slug:        optionalAPISlug(c.Slug),
		Description: c.Description,
		ExpiresAt:   expiresAtParam,
	})
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, token)
}

type updatePersonalAccessTokenCommand struct {
	accountAuthFlags
	PATSlug          string  `arg:"" name:"pat-slug" help:"Personal access token slug." required:""`
	Name             string  `help:"Replacement display name." name:"name" required:""`
	Description      *string `help:"Replacement description." name:"description"`
	ClearDescription bool    `help:"Clear the description." name:"clear-description"`
	ExpiresAt        string  `help:"Replacement RFC3339 expiration timestamp." name:"expires-at"`
	ClearExpiration  bool    `help:"Remove the expiration timestamp." name:"clear-expiration"`
}

func (c *updatePersonalAccessTokenCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	body, err := credentialUpdateBody(
		c.Name,
		c.Description,
		c.ClearDescription,
		c.ExpiresAt,
		c.ClearExpiration,
		nil,
		nil,
	)
	if err != nil {
		return err
	}
	client, err := newAccountAPIClient(c.accountAuthFlags, runtime)
	if err != nil {
		return err
	}
	token, err := client.updatePersonalAccessToken(context.Background(), c.PATSlug, body)
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, token)
}

