package main

import (
	"context"
	"fmt"
	"strings"

	api "github.com/Braidplane/cli/internal/apiclient"
	"github.com/Braidplane/cli/pkg/slug"
	"github.com/Braidplane/cli/pkg/xerror"
)

type alertConnectionCommand struct {
	List       listNotificationConnectionsCommand      `cmd:"" help:"List connections with safe status and workspace/channel metadata."`
	Create     createNotificationConnectionCommand     `cmd:"" help:"Create a managed notification connection; does not authorize Slack yet."`
	Connect    connectNotificationConnectionCommand    `cmd:"" aliases:"reconnect" help:"Start or replace Slack authorization. Prints a private, expiring consent URL; finish consent in your browser, then check list."`
	Disconnect disconnectNotificationConnectionCommand `cmd:"" help:"Disconnect this Braidplane attachment. Other channel attachments remain authorized; in-flight sends may complete."`
}

type listNotificationConnectionsCommand struct{ apiAuthFlags }

func (c *listNotificationConnectionsCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	connections, err := client.listNotificationConnections(context.Background())
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, connections)
}

type createNotificationConnectionCommand struct {
	apiAuthFlags
	Name     string `name:"name" required:"" help:"Notification connection display name."`
	Slug     string `name:"slug" help:"Notification connection slug. Generated by the API when omitted."`
	Provider string `name:"provider" enum:"slack" default:"slack" help:"Notification provider: slack (incoming-webhook only)."`
}

func (c *createNotificationConnectionCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	name, err := requiredAlertName(c.Name)
	if err != nil {
		return err
	}
	var connectionSlug *api.Slug
	if strings.TrimSpace(c.Slug) != "" {
		value, err := slug.New(strings.TrimSpace(c.Slug))
		if err != nil {
			return err
		}
		parsed := value.String()
		connectionSlug = &parsed
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	connection, err := client.createNotificationConnection(context.Background(), api.NewNotificationConnection{
		Name: name, Slug: connectionSlug, Provider: api.NotificationProvider(c.Provider),
	})
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, connection)
}

type connectNotificationConnectionCommand struct {
	apiAuthFlags
	ConnectionSlug string `arg:"" name:"connection-slug" required:"" help:"Connection to authorize or reconnect with a replacement Slack channel."`
}

func (c *connectNotificationConnectionCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	connectionSlug, err := slug.New(c.ConnectionSlug)
	if err != nil {
		return err
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	install, err := client.connectNotificationConnection(context.Background(), connectionSlug.String())
	if err != nil {
		return err
	}
	if _, err := fmt.Fprintln(output.stderr, "Open authorization_url privately in your browser and complete Slack channel consent. Sign in to Braidplane in that browser if needed. This command only starts authorization; check alert connection list afterward. Do not share or log the expiring consent URL."); err != nil {
		return xerror.Unexpected().With(err)
	}
	return writeCLIJSON(output.stdout, install)
}

type disconnectNotificationConnectionCommand struct {
	apiAuthFlags
	ConnectionSlug string `arg:"" name:"connection-slug" required:"" help:"Connection to disconnect locally in Braidplane."`
}

func (c *disconnectNotificationConnectionCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	connectionSlug, err := slug.New(c.ConnectionSlug)
	if err != nil {
		return err
	}
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	metadata, err := client.disconnectNotificationConnection(context.Background(), connectionSlug.String())
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, metadata)
}

func alertDestinationConfig(destinationType string, recipients []string, connection string) (api.AlertDestinationConfig, error) {
	switch destinationType {
	case "email":
		if connection != "" {
			return api.AlertDestinationConfig{}, xerror.ValidationFailed().Detail("--connection-slug is only supported for --type slack")
		}
		return emailAlertDestinationConfig(recipients)
	case "slack":
		if len(recipients) != 0 {
			return api.AlertDestinationConfig{}, xerror.ValidationFailed().Detail("--recipient is only supported for --type email")
		}
		if strings.TrimSpace(connection) == "" {
			return api.AlertDestinationConfig{}, xerror.ValidationFailed().Detail("set --connection-slug for --type slack")
		}
		connectionSlug, err := slug.New(connection)
		if err != nil {
			return api.AlertDestinationConfig{}, err
		}
		config := api.AlertDestinationConfig{}
		if err := config.FromSlackAlertDestinationConfig(api.SlackAlertDestinationConfig{ConnectionSlug: connectionSlug.String()}); err != nil {
			return config, xerror.Unexpected().With(err)
		}
		return config, nil
	default:
		return api.AlertDestinationConfig{}, xerror.ValidationFailed().Detail("type must be email or slack")
	}
}
