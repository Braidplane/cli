func listEnvironmentsParams(limit int32, cursor, direction string, includeDeleted bool) (*api.ListEnvironmentsParams, error) {
	params := &api.ListEnvironmentsParams{}
	if err := applyLimitCursor(limit, cursor, &params.Limit, &params.Cursor); err != nil {
		return nil, err
	}
	if includeDeleted {
		params.IncludeDeleted = &includeDeleted
	}
	if strings.TrimSpace(direction) != "" {
		if direction != string(api.ListEnvironmentsParamsDirectionNext) &&
			direction != string(api.ListEnvironmentsParamsDirectionPrev) {
			return nil, xerror.Unexpected().Detail("direction must be next or prev")
		}
		value := api.ListEnvironmentsParamsDirection(direction)
		params.Direction = &value
	}
	return params, nil
}

