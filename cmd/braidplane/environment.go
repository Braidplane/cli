type updateEnvironmentCommand struct {
	apiAuthFlags

	EnvironmentSlug string `arg:"" name:"environment-slug" help:"Organization environment catalog slug." required:""`
	Name            string `help:"Environment display name." name:"name" required:""`
	Description     string `help:"Operator description." name:"description"`
	Color           string `help:"Environment palette color: blue, amber, red, green, purple, or gray." name:"color"`
	Protected       bool   `help:"Mark the environment as protected." name:"protected"`
	Unprotected     bool   `help:"Mark the environment as unprotected." name:"unprotected"`
	Confirm         string `help:"Exact environment slug required when updating a protected environment." name:"confirm-environment"`
}

func (c *updateEnvironmentCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}

	current, err := client.getEnvironment(context.Background(), c.EnvironmentSlug)
	if err != nil {
		return err
	}
	protected := current.Protected
	if c.Protected && c.Unprotected {
		return xerror.InvalidInput(xerror.Environment).Detail("only one of --protected or --unprotected can be set")
	}
	if c.Protected {
		protected = true
	}
	if c.Unprotected {
		protected = false
	}
	color := current.Color
	if strings.TrimSpace(c.Color) != "" {
		color, err = environmentColorFlag(c.Color)
		if err != nil {
			return err
		}
	}
	environment, err := client.updateEnvironment(context.Background(), c.EnvironmentSlug, api.UpdateEnvironment{
		Name:                             c.Name,
		Description:                      optionalString(c.Description),
		Color:                            color,
		Protected:                        protected,
		ProtectedEnvironmentConfirmation: optionalAPISlug(c.Confirm),
	})
	if err != nil {
		return err
	}

	return writeCLIJSON(output.stdout, environment)
}

// environmentColorFlag normalizes and validates CLI palette values before API submission.
func environmentColorFlag(raw string) (api.EnvironmentColor, error) {
	color := api.EnvironmentColor(strings.ToLower(strings.TrimSpace(raw)))
	if color.Valid() {
		return color, nil
	}
	return "", xerror.InvalidInput(xerror.Environment).
		Detail("environment color must be one of blue, amber, red, green, purple, or gray")
}

