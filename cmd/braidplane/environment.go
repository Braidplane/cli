func applyLimitCursor(limit int32, cursor string, limitTarget **api.LimitParam, cursorTarget **api.CursorParam) error {
	if limit < 0 {
		return xerror.Unexpected().Detail("limit must be zero or greater")
	}
	if limit > 0 {
		value := limit
		*limitTarget = &value
	}
	if strings.TrimSpace(cursor) != "" {
		value := cursor
		*cursorTarget = &value
	}
	return nil
}

func optionalAPISlug(value string) *api.Slug {
	trimmed := strings.TrimSpace(value)
	if trimmed == "" {
		return nil
	}
	return &trimmed
}

func dataSourceRefContract(rawType string, rawCapabilities []string) (api.DataSourceType, []api.DataSourceRefCapability, error) {
	dataSourceType := api.DataSourceType(strings.TrimSpace(rawType))
	if !dataSourceType.Valid() {
		return "", nil, xerror.Unexpected().Detail("data-source-type is invalid")
	}
	if len(rawCapabilities) == 0 {
		return "", nil, xerror.InvalidRequired(xerror.DataSource).Detail("set --capability at least once")
	}

	capabilities := make([]api.DataSourceRefCapability, 0, len(rawCapabilities))
	for _, rawCapability := range rawCapabilities {
		capability := api.DataSourceRefCapability(strings.TrimSpace(rawCapability))
		if !capability.Valid() {
			return "", nil, xerror.Unexpected().Detail("capability must be pipeline_source or pipeline_sink")
		}
		capabilities = append(capabilities, capability)
	}

	return dataSourceType, capabilities, nil
}
