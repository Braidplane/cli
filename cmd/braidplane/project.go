type listProjectsCommand struct {
	apiAuthFlags

	Limit     int32  `help:"Maximum number of projects to return." name:"limit"`
	Cursor    string `help:"Pagination cursor from a previous list response." name:"cursor"`
	SortBy    string `help:"Sort field: project_created_at, project_name, or project_updated_at." name:"sort-by"`
	Order     string `help:"Sort order: asc or desc." name:"order"`
	Direction string `help:"Pagination direction: next or prev." name:"direction"`
}

// Run lists organization projects and writes the paginated JSON response.
func (c *listProjectsCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}

	params, err := listProjectsParams(c.Limit, c.Cursor, c.SortBy, c.Order, c.Direction)
	if err != nil {
		return err
	}
	response, err := client.listProjects(context.Background(), params)
	if err != nil {
		return err
	}

	return writeCLIJSON(output.stdout, response)
}

