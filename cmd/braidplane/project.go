type setProjectPipelineBackendCommand struct {
	apiAuthFlags

	ProjectSlug    string `arg:"" name:"project-slug" help:"Project slug." required:""`
	DataSource     string `help:"Git-compatible data source slug." name:"data-source" required:""`
	TrackedBranch  string `help:"Writable tracked branch for reconcile, publish, transfer, and delete routing." name:"tracked-branch" required:""`
	PipelineDir    string `help:"Repository-relative pipeline directory." name:"pipeline-dir" default:"pipelines"`
	Mode           string `help:"Backend attach mode: adopt_existing or create_from_template." name:"mode" required:""`
	ProviderOwner  string `help:"GitHub user or organization for create_from_template." name:"provider-owner"`
	RepositoryName string `help:"Private GitHub repository name for create_from_template." name:"repository-name"`
}

// Run validates the requested attach mode and sets the project pipeline backend.
func (c *setProjectPipelineBackendCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}

	mode := api.SetProjectPipelineBackendRequestMode(strings.TrimSpace(c.Mode))
	if !mode.Valid() {
		return xerror.ValidationFailed().Detail("mode must be adopt_existing or create_from_template")
	}
	var owner, repositoryName *string
	if mode == api.SetProjectPipelineBackendRequestModeCreateFromTemplate {
		if strings.TrimSpace(c.ProviderOwner) == "" || strings.TrimSpace(c.RepositoryName) == "" {
			return xerror.ValidationFailed().Detail("provider-owner and repository-name are required for create_from_template")
		}
		owner, repositoryName = &c.ProviderOwner, &c.RepositoryName
	}
	project, err := client.setProjectPipelineBackend(context.Background(), c.ProjectSlug, api.SetProjectPipelineBackendRequest{
		DataSourceSlug: c.DataSource,
		TrackedBranch:  c.TrackedBranch,
		PipelineDir:    c.PipelineDir,
		ProviderOwner:  owner,
		RepositoryName: repositoryName,
		Mode:           mode,
	})
	if err != nil {
		return err
	}

	return writeCLIJSON(output.stdout, project)
}

// listProjectsParams validates list flags and maps them onto generated API query parameters.
func listProjectsParams(limit int32, cursor, sortBy, order, direction string) (*api.ListProjectsParams, error) {
	params := &api.ListProjectsParams{}
	if err := applyLimitCursor(limit, cursor, &params.Limit, &params.Cursor); err != nil {
		return nil, err
	}
	if sortBy := strings.TrimSpace(sortBy); sortBy != "" {
		value := api.ListProjectsParamsSortBy(sortBy)
		if !value.Valid() {
			return nil, xerror.ValidationFailed().Detail("sort-by must be project_created_at, project_name, or project_updated_at")
		}
		params.SortBy = &value
	}
	if order := strings.TrimSpace(order); order != "" {
		value := api.ListProjectsParamsOrder(order)
		if !value.Valid() {
			return nil, xerror.ValidationFailed().Detail("order must be asc or desc")
		}
		params.Order = &value
	}
	if direction := strings.TrimSpace(direction); direction != "" {
		value := api.ListProjectsParamsDirection(direction)
		if !value.Valid() {
			return nil, xerror.ValidationFailed().Detail("direction must be next or prev")
		}
		params.Direction = &value
	}

	return params, nil
}
