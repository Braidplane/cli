type updateOrganizationRetentionCommand struct {
	apiAuthFlags
	QueryExecutionRetentionDays   int `help:"Days to retain saved query executions." name:"query-execution-retention-days" required:""`
	ReplayCheckpointRetentionDays int `help:"Days to retain replay checkpoints." name:"replay-checkpoint-retention-days" required:""`
	RunHistoryRetentionDays       int `help:"Days to retain completed pipeline runs." name:"run-history-retention-days" required:""`
	EventLogRetentionDays         int `help:"Days to retain durable event logs." name:"event-log-retention-days" required:""`
}

func (c *updateOrganizationRetentionCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, err := newAPIClient(c.apiAuthFlags, runtime)
	if err != nil {
		return err
	}
	policy, err := client.updateOrganizationRetentionPolicy(context.Background(), api.OrganizationRetentionPolicy{
		QueryExecutionRetentionDays:   c.QueryExecutionRetentionDays,
		ReplayCheckpointRetentionDays: c.ReplayCheckpointRetentionDays,
		RunHistoryRetentionDays:       c.RunHistoryRetentionDays,
		EventLogRetentionDays:         c.EventLogRetentionDays,
	})
	if err != nil {
		return err
	}
	return writeCLIJSON(output.stdout, policy)
}

