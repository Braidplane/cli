// Run lists environment-scoped pipeline trigger definitions.
func (c *listPipelineTriggersCommand) Run(output *cliOutput, runtime *cliRuntime) error {
	client, projectSlug, environmentSlug, err := newPipelineEnvironmentAPIClient(
		c.apiPipelineFlags,
		c.Environment,
		runtime,
	)
	if err != nil {
		return err
	}

	params, err := listPipelineTriggersParams(c.Limit, c.Cursor)
	if err != nil {
		return err
	}
	triggers, err := client.listPipelineTriggers(context.Background(), projectSlug, environmentSlug, params)
	if err != nil {
		return xerror.Wrapf("list pipeline triggers: %w", err)
	}

	return writeCLIJSON(output.stdout, triggers)
}

