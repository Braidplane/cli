type pipelineTriggerAPIPayload struct {
	name             string
	enabled          bool
	pipelineSlug     api.Slug
	versionPolicy    api.PipelineTriggerVersionPolicy
	runtimeInputKeys []string
	retryPolicy      api.PipelineTriggerRetryPolicy
	triggerType      api.PipelineTriggerType
	schedule         *api.PipelineTriggerScheduleConfig
	webhook          *api.PipelineWebhookConfigInput
	completion       *api.PipelineTriggerCompletionConfig
}

// apiPayload validates trigger flags and returns the common API payload fields.
func (f pipelineTriggerPayloadFlags) apiPayload() (pipelineTriggerAPIPayload, error) {
	enabled, err := explicitTriggerEnabled(f.Enabled, f.Disabled)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}
	versionPolicy, err := pipelineTriggerVersionPolicy(f.VersionPolicy, f.PinnedVersionHash)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}
	runtimeInputKeys, err := pipelineTriggerRuntimeInputKeys(f.RuntimeInputKey)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}
	retryPolicy, err := pipelineTriggerRetryPolicy(f)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}
	triggerType := api.PipelineTriggerType(strings.TrimSpace(f.Type))
	completion, err := f.completionConfig(triggerType)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}
	schedule, webhook, err := pipelineTriggerTypeConfig(f, triggerType, runtimeInputKeys)
	if err != nil {
		return pipelineTriggerAPIPayload{}, err
	}

	return pipelineTriggerAPIPayload{
		name:             strings.TrimSpace(f.Name),
		enabled:          enabled,
		pipelineSlug:     strings.TrimSpace(f.PipelineSlug),
		versionPolicy:    versionPolicy,
		runtimeInputKeys: runtimeInputKeys,
		retryPolicy:      retryPolicy,
		triggerType:      triggerType,
		schedule:         schedule,
		webhook:          webhook,
		completion:       completion,
	}, nil
}

func (f pipelineTriggerPayloadFlags) completionConfig(triggerType api.PipelineTriggerType) (*api.PipelineTriggerCompletionConfig, error) {
	if triggerType != api.PipelineTriggerTypeCompletion {
		if f.UpstreamPipeline != "" || f.CompletionCondition != "" || f.ExecutionGrantEnabled || f.ExecutionGrantDisabled {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("completion flags require --type completion")
		}
		return nil, nil //nolint:nilnil // Schedule and webhook payloads must omit completion configuration.
	}
	upstream, err := slug.New(strings.TrimSpace(f.UpstreamPipeline))
	if err != nil {
		return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("completion triggers require a valid --upstream-pipeline slug")
	}
	condition := api.PipelineCompletionCondition(strings.TrimSpace(f.CompletionCondition))
	if condition != api.PipelineCompletionConditionSuccess && condition != api.PipelineCompletionConditionFinalFailure {
		return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("completion triggers require --completion-condition success or final_failure")
	}
	if f.ExecutionGrantEnabled == f.ExecutionGrantDisabled {
		return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("set exactly one of --execution-grant-enabled or --execution-grant-disabled")
	}
	return &api.PipelineTriggerCompletionConfig{
		UpstreamPipelineSlug: upstream.String(), Condition: condition, ExecutionGrantEnabled: f.ExecutionGrantEnabled,
	}, nil
}

func pipelineTriggerTypeConfig(
	f pipelineTriggerPayloadFlags,
	triggerType api.PipelineTriggerType,
	runtimeInputKeys []string,
) (*api.PipelineTriggerScheduleConfig, *api.PipelineWebhookConfigInput, error) {
	switch triggerType {
	case api.PipelineTriggerTypeCompletion:
		if strings.TrimSpace(f.Cron) != "" || strings.TrimSpace(f.Timezone) != "" || strings.TrimSpace(f.MisfirePolicy) != "" || len(f.WebhookInputMapping) > 0 {
			return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("completion triggers must not set schedule or webhook flags")
		}
		return nil, nil, nil
	case api.PipelineTriggerTypeSchedule:
		if len(f.WebhookInputMapping) > 0 {
			return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("schedule triggers must not set --webhook-input-mapping")
		}
		if strings.TrimSpace(f.Cron) == "" || strings.TrimSpace(f.Timezone) == "" || strings.TrimSpace(f.MisfirePolicy) == "" {
			return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("schedule triggers require --cron, --timezone, and --misfire-policy")
		}
		misfirePolicy := api.PipelineTriggerScheduleMisfirePolicy(strings.TrimSpace(f.MisfirePolicy))
		if !misfirePolicy.Valid() {
			return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("misfire-policy must be skip or fire_once")
		}
		return &api.PipelineTriggerScheduleConfig{
			Cron:          strings.TrimSpace(f.Cron),
			Timezone:      strings.TrimSpace(f.Timezone),
			MisfirePolicy: misfirePolicy,
		}, nil, nil
	case api.PipelineTriggerTypeWebhook:
		if strings.TrimSpace(f.Cron) != "" || strings.TrimSpace(f.Timezone) != "" || strings.TrimSpace(f.MisfirePolicy) != "" {
			return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("webhook triggers must not set --cron, --timezone, or --misfire-policy")
		}
		mappings, err := pipelineWebhookInputMappings(f.WebhookInputMapping, runtimeInputKeys)
		if err != nil {
			return nil, nil, err
		}
		return nil, &api.PipelineWebhookConfigInput{InputMappings: mappings}, nil
	default:
		return nil, nil, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("type must be schedule, webhook, or completion")
	}
}

func pipelineWebhookInputMappings(
	rawMappings []string,
	runtimeInputKeys []string,
) ([]api.PipelineWebhookInputMapping, error) {
	if len(rawMappings) > 100 {
		return nil, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("at most 100 webhook input mappings may be set")
	}
	allowedKeys := make(map[string]struct{}, len(runtimeInputKeys))
	for _, key := range runtimeInputKeys {
		allowedKeys[key] = struct{}{}
	}
	seenPointers := map[string]struct{}{}
	seenKeys := map[string]struct{}{}
	mappings := make([]api.PipelineWebhookInputMapping, 0, len(rawMappings))
	for _, rawMapping := range rawMappings {
		separator := strings.LastIndexByte(rawMapping, '=')
		if separator < 0 {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("webhook-input-mapping must use <json-pointer>=<runtime-input-key>")
		}
		pointer := rawMapping[:separator]
		key := strings.TrimSpace(rawMapping[separator+1:])
		if len(pointer) > 500 {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("webhook json pointer must be at most 500 characters")
		}
		if _, err := jsonpointer.New(pointer); err != nil {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("webhook json pointer is invalid")
		}
		if err := pipelineruntimevars.ValidateInputKey(key); err != nil {
			return nil, err
		}
		if _, ok := allowedKeys[key]; !ok {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detailf("webhook mapping runtime input %q is not declared", key)
		}
		if _, ok := seenPointers[pointer]; ok {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("webhook json pointer mappings must be unique")
		}
		if _, ok := seenKeys[key]; ok {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).Detail("webhook runtime input mappings must be unique")
		}
		seenPointers[pointer] = struct{}{}
		seenKeys[key] = struct{}{}
		mappings = append(mappings, api.PipelineWebhookInputMapping{JsonPointer: pointer, RuntimeInputKey: key})
	}
	sort.Slice(mappings, func(left, right int) bool {
		return mappings[left].JsonPointer < mappings[right].JsonPointer
	})
	return mappings, nil
}

// explicitTriggerEnabled requires callers to choose enabled state intentionally.
func explicitTriggerEnabled(enabled, disabled bool) (bool, error) {
	switch {
	case enabled && disabled:
		return false, xerror.InvalidInput(xerror.PipelineTrigger).Detail("only one of --enabled or --disabled can be set")
	case enabled:
		return true, nil
	case disabled:
		return false, nil
	default:
		return false, xerror.InvalidInput(xerror.PipelineTrigger).Detail("set --enabled or --disabled")
	}
}

// pipelineTriggerVersionPolicy validates version-policy flag combinations.
func pipelineTriggerVersionPolicy(mode, pinnedVersionHash string) (api.PipelineTriggerVersionPolicy, error) {
	trimmedMode := strings.TrimSpace(mode)
	trimmedHash := strings.TrimSpace(pinnedVersionHash)
	policy := api.PipelineTriggerVersionPolicy{
		Mode: api.PipelineTriggerVersionPolicyMode(trimmedMode),
	}
	switch policy.Mode {
	case api.PipelineTriggerVersionPolicyModeLatestDeployed:
		if trimmedHash != "" {
			return api.PipelineTriggerVersionPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("latest_deployed version policy must not set --pinned-version-hash")
		}
	case api.PipelineTriggerVersionPolicyModePinned:
		if trimmedHash == "" {
			return api.PipelineTriggerVersionPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("pinned version policy requires --pinned-version-hash")
		}
		policy.PinnedVersionHash = &trimmedHash
	default:
		return api.PipelineTriggerVersionPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("version-policy must be latest_deployed or pinned")
	}

	return policy, nil
}

// pipelineTriggerRuntimeInputKeys validates and normalizes repeated runtime input key flags.
func pipelineTriggerRuntimeInputKeys(rawKeys []string) ([]string, error) {
	if len(rawKeys) == 0 {
		return []string{}, nil
	}
	seen := map[string]struct{}{}
	keys := make([]string, 0, len(rawKeys))
	for _, rawKey := range rawKeys {
		key := strings.TrimSpace(rawKey)
		if err := pipelineruntimevars.ValidateInputKey(key); err != nil {
			return nil, err
		}
		if _, ok := seen[key]; ok {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detailf("runtime input key %q was provided more than once", key)
		}
		seen[key] = struct{}{}
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys, nil
}

// pipelineTriggerRetryPolicy validates retry flags and returns the API policy shape.
func pipelineTriggerRetryPolicy(f pipelineTriggerPayloadFlags) (api.PipelineTriggerRetryPolicy, error) {
	if f.RetryMaxAttempts < 1 {
		return api.PipelineTriggerRetryPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("retry-max-attempts must be one or greater")
	}
	if f.RetryInitialDelaySeconds < 0 || f.RetryMaxDelaySeconds < 0 || f.RetryMaxElapsedSeconds < 0 {
		return api.PipelineTriggerRetryPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("retry delay values must be zero or greater")
	}
	backoff := api.PipelineTriggerBackoffStrategy(f.RetryBackoff)
	if !backoff.Valid() {
		return api.PipelineTriggerRetryPolicy{}, xerror.InvalidInput(xerror.PipelineTrigger).
			Detail("retry-backoff must be none, fixed, or exponential")
	}
	failureKinds, err := pipelineTriggerRetryFailureKinds(f.RetryFailureKind)
	if err != nil {
		return api.PipelineTriggerRetryPolicy{}, err
	}

	policy := api.PipelineTriggerRetryPolicy{
		Enabled:               f.RetryEnabled,
		MaxAttempts:           f.RetryMaxAttempts,
		BackoffStrategy:       backoff,
		InitialDelaySeconds:   f.RetryInitialDelaySeconds,
		MaxDelaySeconds:       f.RetryMaxDelaySeconds,
		Jitter:                f.RetryJitter,
		RetryableFailureKinds: failureKinds,
	}
	if f.RetryMaxElapsedSeconds > 0 {
		maxElapsed := f.RetryMaxElapsedSeconds
		policy.MaxElapsedSeconds = &maxElapsed
	}
	return policy, nil
}

// pipelineTriggerRetryFailureKinds validates and sorts repeated retry failure kind flags.
func pipelineTriggerRetryFailureKinds(rawKinds []string) ([]api.PipelineTriggerRetryFailureKind, error) {
	if len(rawKinds) == 0 {
		return []api.PipelineTriggerRetryFailureKind{}, nil
	}
	seen := map[api.PipelineTriggerRetryFailureKind]struct{}{}
	kinds := make([]api.PipelineTriggerRetryFailureKind, 0, len(rawKinds))
	for _, rawKind := range rawKinds {
		kind := api.PipelineTriggerRetryFailureKind(strings.TrimSpace(rawKind))
		if !kind.Valid() {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detail("retry-failure-kind must be data_source or platform")
		}
		if _, ok := seen[kind]; ok {
			return nil, xerror.InvalidInput(xerror.PipelineTrigger).
				Detailf("retry failure kind %q was provided more than once", kind)
		}
		seen[kind] = struct{}{}
		kinds = append(kinds, kind)
	}
	sort.Slice(kinds, func(left, right int) bool {
		return kinds[left] < kinds[right]
	})
	return kinds, nil
}

