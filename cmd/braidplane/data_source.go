func (f dataSourceRequestFlags) snowflakeConfig(required bool) (api.SnowflakeConfig, error) {
	if required {
		if err := requireFields(map[string]string{
			"--account": f.Account, "--warehouse": f.Warehouse,
			"--database": f.Database, "--schema": f.Schema,
		}); err != nil {
			return api.SnowflakeConfig{}, err
		}
	}
	if f.ConnectTimeout != 0 && (f.ConnectTimeout < 1 || f.ConnectTimeout > 300) {
		return api.SnowflakeConfig{}, xerror.InvalidInput(xerror.DataSource).Detail(
			"connect-timeout must be between 1 and 300 seconds",
		)
	}
	var objects *[]api.SnowflakeObjectGrant
	if len(f.WIFSelectTables)+len(f.WIFInsertTables) > 0 {
		selected := []api.SnowflakeObjectGrant{}
		for _, name := range f.WIFSelectTables {
			selected = append(selected, api.SnowflakeObjectGrant{Name: name, Privilege: api.SELECT})
		}
		for _, name := range f.WIFInsertTables {
			selected = append(selected, api.SnowflakeObjectGrant{Name: name, Privilege: api.INSERT})
		}
		objects = &selected
	}

	return api.SnowflakeConfig{
		Account: f.Account, Warehouse: f.Warehouse, Database: f.Database, Schema: f.Schema,
		WifObjects: objects,
		Role:       optionalString(f.Role), ConnectTimeout: optionalPositiveInt(f.ConnectTimeout),
	}, nil
}

