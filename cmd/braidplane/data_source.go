// listDataSourcesParams converts CLI pagination and sort flags into generated query params.
func listDataSourcesParams(limit int32, cursor, sortBy, order, direction string) (*api.ListDataSourcesParams, error) {
	params := &api.ListDataSourcesParams{}
	if err := applyLimitCursor(limit, cursor, &params.Limit, &params.Cursor); err != nil {
		return nil, err
	}
	if value := strings.TrimSpace(sortBy); value != "" {
		enumValue := api.ListDataSourcesParamsSortBy(value)
		if !enumValue.Valid() {
			return nil, xerror.InvalidInput(xerror.DataSource).Detail("sort-by must be data_source_created_at, data_source_updated_at, or data_source_name")
		}
		params.SortBy = &enumValue
	}
	if value := strings.TrimSpace(order); value != "" {
		enumValue := api.ListDataSourcesParamsOrder(value)
		if !enumValue.Valid() {
			return nil, xerror.InvalidInput(xerror.DataSource).Detail("order must be asc or desc")
		}
		params.Order = &enumValue
	}
	if value := strings.TrimSpace(direction); value != "" {
		enumValue := api.ListDataSourcesParamsDirection(value)
		if !enumValue.Valid() {
			return nil, xerror.InvalidInput(xerror.DataSource).Detail("direction must be next or prev")
		}
		params.Direction = &enumValue
	}
	return params, nil
}

