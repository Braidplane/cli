// updateBody builds the generated OpenAPI update body for mutable fields.
func (c *updateDataSourceCommand) updateBody() (api.UpdateDataSourceRequest, string, error) {
	if strings.TrimSpace(c.RequestFile) != "" {
		if c.Active != nil {
			return api.UpdateDataSourceRequest{}, "", xerror.InvalidInput(xerror.DataSource).Detail("do not combine --active with --file")
		}
		if err := c.rejectMixedFileInput(c.Type, c.DataSourceSlug); err != nil {
			return api.UpdateDataSourceRequest{}, "", err
		}
		return updateDataSourceBodyFromFile(c.RequestFile)
	}
	if strings.TrimSpace(c.Type) == "" {
		return api.UpdateDataSourceRequest{}, "", xerror.InvalidRequired(xerror.DataSource).Detail("set type or --file")
	}
	if strings.TrimSpace(c.DataSourceSlug) == "" {
		return api.UpdateDataSourceRequest{}, "", xerror.InvalidRequired(xerror.DataSource).Detail("set data-source-slug or --file")
	}
	dataSourceType, err := parseDataSourceType(c.Type)
	if err != nil {
		return api.UpdateDataSourceRequest{}, "", err
	}
	if err := c.validateReadOnlyMode(); err != nil {
		return api.UpdateDataSourceRequest{}, "", err
	}

	body := api.UpdateDataSourceRequest{IsActive: c.Active}
	if name := strings.TrimSpace(c.Name); name != "" {
		body.Name = &name
	}
	readOnly := c.createReadOnlyPointer()
	if readOnly != nil {
		body.ReadOnly = readOnly
	}
	config, hasConfig, err := c.updateConfig(dataSourceType)
	if err != nil {
		return api.UpdateDataSourceRequest{}, "", err
	}
	if hasConfig {
		body.Config = &config
	}
	if body.Name == nil && body.Config == nil && body.ReadOnly == nil && body.IsActive == nil {
		return api.UpdateDataSourceRequest{}, "", xerror.InvalidRequired(xerror.DataSource).
			Detail("set --name, config flags, --read-only, --read-write, or --active")
	}

	return body, c.DataSourceSlug, nil
}

